#!/usr/bin/env node
/**
 * Generates supabase/migrations/018_seed_plz_coordinates.sql from the GeoNames
 * German postal code dump (CC BY 4.0, https://www.geonames.org/).
 *
 * A PLZ can cover several places, so its coordinates are the average of all
 * GeoNames entries for that PLZ. Requires the `unzip` CLI.
 *
 * Usage: node next-app/scripts/generate-plz-seed.mjs
 */
import { execFileSync } from 'node:child_process';
import { mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const SOURCE_URL = 'https://download.geonames.org/export/zip/DE.zip';
const BATCH_SIZE = 500;

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const outFile = path.resolve(scriptDir, '../../supabase/migrations/018_seed_plz_coordinates.sql');

const response = await fetch(SOURCE_URL);
if (!response.ok) throw new Error(`Download failed: ${response.status} ${response.statusText}`);

const workDir = mkdtempSync(path.join(tmpdir(), 'plz-seed-'));
let rows;
try {
  const zipPath = path.join(workDir, 'DE.zip');
  writeFileSync(zipPath, Buffer.from(await response.arrayBuffer()));
  rows = execFileSync('unzip', ['-p', zipPath, 'DE.txt'], { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 })
    .split('\n')
    .filter(Boolean);
} finally {
  rmSync(workDir, { recursive: true, force: true });
}

// Columns: country, postal code, place, admin1..3 (name, code), lat, lng, accuracy
const sums = new Map();
for (const row of rows) {
  const cols = row.split('\t');
  const plz = cols[1];
  const lat = Number(cols[9]);
  const lng = Number(cols[10]);
  if (!/^\d{5}$/.test(plz) || !Number.isFinite(lat) || !Number.isFinite(lng)) continue;
  const entry = sums.get(plz) ?? { lat: 0, lng: 0, n: 0 };
  entry.lat += lat;
  entry.lng += lng;
  entry.n += 1;
  sums.set(plz, entry);
}

const values = [...sums.entries()]
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([plz, { lat, lng, n }]) => `('${plz}', ${(lat / n).toFixed(4)}, ${(lng / n).toFixed(4)})`);

const batches = [];
for (let i = 0; i < values.length; i += BATCH_SIZE) {
  batches.push(
    'INSERT INTO public.plz_coordinates (plz, lat, lng) VALUES\n'
      + values.slice(i, i + BATCH_SIZE).join(',\n')
      + '\nON CONFLICT (plz) DO NOTHING;',
  );
}

const sql = `-- Migration 018: Seed plz_coordinates (${values.length} German postal codes)
-- GENERATED by next-app/scripts/generate-plz-seed.mjs — do not edit by hand.
-- Source: GeoNames postal codes (${SOURCE_URL}), licensed CC BY 4.0.
-- Coordinates are the average of all GeoNames places sharing a PLZ.

${batches.join('\n\n')}

-- Backfill distance for existing leads (fires trg_estimations_distance;
-- status is unchanged, so the lifecycle trigger lets it through).
UPDATE public.estimations SET postal_code = postal_code WHERE postal_code IS NOT NULL;
`;

writeFileSync(outFile, sql);
console.log(`Wrote ${values.length} PLZs to ${path.relative(process.cwd(), outFile)}`);
